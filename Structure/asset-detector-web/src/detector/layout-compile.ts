import { LayoutBreakpoint, LayoutFile, ElementOverride, validateLayout } from "./layout-schema";

/**
 * The template switches its scale base at 768/769px (ClientLayoutContainer),
 * so these ranges follow that split: desktop > 768, tablet 481–768, mobile <= 480.
 */
export const BREAKPOINT_MEDIA: Record<LayoutBreakpoint, string> = {
  desktop: "(min-width: 769px)",
  tablet: "(min-width: 481px) and (max-width: 768px)",
  mobile: "(max-width: 480px)",
};

function declarations(o: ElementOverride): string[] {
  const d: string[] = [];
  // The template positions with top/left/right/bottom utilities; setting left/top
  // while its right/bottom stay would stretch the element, so release them.
  // transform is never written: the template's own translate(-50%) stays intact.
  if (o.left !== undefined) d.push(`left: ${o.left.trim()}`, "right: auto");
  if (o.top !== undefined) d.push(`top: ${o.top.trim()}`, "bottom: auto");
  if (o.width !== undefined) d.push(`width: ${o.width.trim()}`);
  if (o.height !== undefined) d.push(`height: ${o.height.trim()}`);
  // the individual `scale` property scales the element and everything in it (pictures with fixed sizes,
  // groups of pictures) and composes with the template's own transform, which is never written.
  if (o.scaleX !== undefined || o.scaleY !== undefined) d.push(`scale: ${o.scaleX ?? 1} ${o.scaleY ?? 1}`);
  if (o.zIndex !== undefined) d.push(`z-index: ${o.zIndex}`);
  if (o.hidden === true) d.push("display: none");
  return d;
}

/**
 * Doubling the attribute selector gives specificity (0,2,0): it beats Tailwind
 * utilities (0,1,0) whatever the stylesheet order, without !important.
 * Inline styles still win — see 14-PLAN section 8.
 */
function selector(id: string): string {
  return `[data-edit-id="${id}"][data-edit-id]`;
}

/** Compiles a layout into CSS. Throws on an invalid layout (the value goes into CSS). */
export function compileLayoutCss(layout: LayoutFile): string {
  const errors = validateLayout(layout);
  if (errors.length) throw new Error(`Invalid layout: ${errors.join("; ")}`);

  const out: string[] = ["/* generated by visual editing - do not edit */"];
  for (const bp of ["desktop", "tablet", "mobile"] as LayoutBreakpoint[]) {
    const rules: string[] = [];
    for (const [id, el] of Object.entries(layout.elements).sort(([a], [b]) => a.localeCompare(b))) {
      const o = el.overrides[bp];
      if (!o) continue;
      const d = declarations(o);
      if (d.length) rules.push(`  ${selector(id)} { ${d.join("; ")}; }`);
    }
    if (rules.length) out.push(`@media ${BREAKPOINT_MEDIA[bp]} {\n${rules.join("\n")}\n}`);
  }
  return out.join("\n") + "\n";
}
